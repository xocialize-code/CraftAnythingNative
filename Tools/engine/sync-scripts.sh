#!/bin/sh
# Copy the engine's website page scripts into Sources/CraftWebKit/PageScripts.swift, so the WebKit
# browser tools run exactly the scripts the pinned engine runs in Chromium.
#   Tools/engine/sync-scripts.sh [path to the craft-anything clone]   (default: ../craft-anything)
set -eu
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
. "$here/pin.env"
clone=${1:-"$root/../craft-anything"}
dir=website_js
out="$root/Sources/CraftWebKit/PageScripts.swift"

{
    echo "// Generated by Tools/engine/sync-scripts.sh from the pinned engine ($CRAFT_ANYTHING_COMMIT):"
    echo "// crates/engine/src/tools/$dir in storytold/craft-anything, MIT OR Apache-2.0. Don't edit."
    echo
    echo "/// The read-only scripts the engine's website tools run in the page."
    echo "enum PageScripts {"
    for name in blueprint layout find_states state click_state; do
        var=$(echo "$name" | awk -F_ '{for (i = 1; i <= NF; i++) out = out (i == 1 ? $i : toupper(substr($i, 1, 1)) substr($i, 2)); print out}')
        echo "    static let $var = ###\"\"\""
        git -C "$clone" show "$CRAFT_ANYTHING_COMMIT:crates/engine/src/tools/$dir/$name.js"
        echo "\"\"\"###"
    done
    echo "}"
} > "$out.new"
mv -f "$out.new" "$out"
echo "Wrote $out"
